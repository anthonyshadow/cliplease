// `bun run cn:tables`: compiles cn's class-merge tables once into src/lib/cn-tables.ts, so the browser loads the engine
// and its tables instead of compiling them on every page load. The config is the one cn/config used at runtime: every
// default class group plus the type scale as font sizes, since cn's defaults read `text-body` as a color and would drop
// it next to `text-ink`. src/lib/cn-tables.test.ts fails when the committed file differs from what this compiles.
import { writeFileSync } from "node:fs";
import { compileToSource, mergeConfigs } from "cn/compiler";
import { defaultConfig } from "cn/config";
import { TYPE_SCALE } from "../src/lib/type-scale";

export const CN_TABLES = "src/lib/cn-tables.ts";

const BANNER = `// GENERATED by \`bun run cn:tables\` (scripts/cn-tables.ts) — do not edit.`;

/** The tables module's source. */
export function cnTablesSource(): string {
  const config = mergeConfigs(defaultConfig(), {
    extend: { classGroups: { "font-size": [{ text: [...TYPE_SCALE] }] } },
  });
  return compileToSource(config, { lang: "ts", banner: BANNER });
}

if (require.main === module) {
  writeFileSync(CN_TABLES, cnTablesSource());
  console.log(`cn:tables: wrote ${CN_TABLES}`);
}
