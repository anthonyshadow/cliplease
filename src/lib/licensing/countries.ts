export const COUNTRIES: readonly Country[] = ROWS.map(
  ([code, name, region, the = false]) => ({ code, name, region, the }),
);

const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

/** The country with ISO code `code`, or undefined (the DB accepts any two letters, so stored rows may hold others). */
export const countryOf = (code: string) => BY_CODE.get(code);

/** The country's name, or the code itself when it isn't listed: scope labels read stored rows and never throw. */
export const countryName = (code: string) => countryOf(code)?.name ?? code;

/** The country as a sentence names it: "the United States", "France". */
export const countryInSentence = (code: string) => {
  const country = countryOf(code);
  if (!country) return code;
  return country.the ? `the ${country.name}` : country.name;
};

/** The names in a region, in list order, for "Which countries?" (05 §4.1 callout 19). */
export const countryNamesIn = (region: RegionKey) =>
  COUNTRIES.filter((c) => c.region === region).map((c) => c.name);
